#!/usr/bin/env node
// Bounded parse-time regression test for the E7 property-drawer
// look-ahead (src/prepass.c classify_line, src/scanner.c
// propdrawer_body_is_valid).
//
// A run of N nested `:PROPERTIES:` lines followed by a disqualifying
// line used to re-trigger the whole-body look-ahead once per nested
// occurrence (each `:PROPERTIES:` line, reclassified as a fresh
// property-drawer candidate while already inside the previous one's
// degraded plain-drawer body, launched its own O(remaining-lines) peek
// with no memoization) - O(N^2) total. classify_line now only treats
// `:PROPERTIES:` as a property-drawer candidate directly under a
// headline or inlinetask, never as general drawer/block body content,
// which stops nested occurrences from ever reaching the look-ahead at
// all. This input is far beyond adversarial-no-error.js's own
// MAX_INPUT_LEN (4096 bytes, ~300 `:PROPERTIES:` lines) and would not
// be generated by that harness, so it needs its own bounded check.
'use strict';

const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const os = require('os');

const treeSitterBin = path.resolve('node_modules/.bin/tree-sitter');

const N = 8000;
const TIMEOUT_MS = 3000;   // fixed: ~15-50ms. pre-fix at N=8000: ~4.1s.

const input = '* H\n' + ':PROPERTIES:\n'.repeat(N) + 'bad\n';
const tmp = path.join(os.tmpdir(), `org-propdrawer-stress-${process.pid}.org`);
fs.writeFileSync(tmp, input);

const start = Date.now();
const r = cp.spawnSync(treeSitterBin, ['parse', '-q', tmp], {
  encoding: 'utf8',
  timeout: TIMEOUT_MS,
  killSignal: 'SIGKILL',
});
const elapsed = Date.now() - start;
fs.unlinkSync(tmp);

if (r.error && r.error.code === 'ETIMEDOUT') {
  console.log(`FAIL  propdrawer stress: N=${N} did not terminate within ${TIMEOUT_MS}ms (quadratic regression?)`);
  process.exit(1);
}
if (r.signal || r.status === null) {
  console.log(`FAIL  propdrawer stress: N=${N} parse aborted (signal=${r.signal})`);
  process.exit(1);
}

console.log(`PASS  propdrawer stress: N=${N} lines parsed in ${elapsed}ms (bound ${TIMEOUT_MS}ms)`);
process.exit(0);
